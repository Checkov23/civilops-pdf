//! CivilOps PDF: the German interface (Deutsch).
//!
//! [`EXACT`] maps whole labels. [`TEMPLATES`] map labels with variable parts: in the English
//! pattern every `{…}` is a placeholder (as in the `format!` that made the label); in the German
//! one `{}` takes the placeholders in order, `{1}` picks one by position, and `{1|Seite|Seiten}`
//! chooses the singular when that placeholder is `1`. Placeholders that are themselves labels
//! ("Undo {}" with "Rotate page") are translated too.

use std::collections::HashMap;
use std::sync::{LazyLock, Mutex};

/// A German label for `text`, if there is one.
pub(super) fn exact(text: &str) -> Option<&'static str> {
    static MAP: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| EXACT.iter().copied().collect());
    MAP.get(text).copied()
}

/// `text` in German, if it is a known label or matches a template.
pub(super) fn translate(text: &str) -> Option<String> {
    if text.len() < 2 || !text.bytes().any(|b| b.is_ascii_alphabetic()) {
        return None;
    }
    if let Some(t) = exact(text) {
        return Some(t.to_string());
    }
    // Section headings drawn in capitals ("MODIFY PAGE"): the label's German, in capitals.
    static UPPER: LazyLock<HashMap<String, String>> = LazyLock::new(|| EXACT.iter().map(|(en, de)| (en.to_uppercase(), de.to_uppercase())).collect());
    if text.chars().any(char::is_alphabetic)
        && !text.chars().any(char::is_lowercase)
        && let Some(t) = UPPER.get(text)
    {
        return Some(t.clone());
    }
    // Lists joined with " · " ("Rotate pages · Insert pages"): each part on its own.
    if text.contains(" · ") {
        let joined = text.split(" · ").map(|p| exact(p).unwrap_or(p)).collect::<Vec<_>>().join(" · ");
        if joined != text {
            return Some(joined);
        }
    }
    static MEMO: LazyLock<Mutex<HashMap<String, Option<String>>>> = LazyLock::new(|| Mutex::new(HashMap::new()));
    if let Ok(memo) = MEMO.lock()
        && let Some(hit) = memo.get(text)
    {
        return hit.clone();
    }
    let result = templated(text, 0);
    if let Ok(mut memo) = MEMO.lock() {
        // Bounded: labels with counters and names change while the app runs.
        if memo.len() > 20_000 {
            memo.clear();
        }
        memo.insert(text.to_string(), result.clone());
    }
    result
}

enum Piece {
    Text(&'static str),
    Arg(usize),
    Plural(usize, &'static str, &'static str),
}

struct Template {
    /// The English pattern's literal parts (one more than its placeholders).
    parts: Vec<&'static str>,
    kinds: Vec<Kind>,
    german: Vec<Piece>,
}

/// Split an English pattern at its `{…}` placeholders.
fn english_parts(p: &'static str) -> Vec<&'static str> {
    let mut parts = Vec::new();
    let mut rest = p;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}') else { break };
        parts.push(&rest[..open]);
        rest = &rest[open + close + 1..];
    }
    parts.push(rest);
    parts
}

fn german_pieces(p: &'static str) -> Vec<Piece> {
    let mut out = Vec::new();
    let mut next = 0;
    let mut rest = p;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}') else { break };
        if open > 0 {
            out.push(Piece::Text(&rest[..open]));
        }
        let inner = &rest[open + 1..open + close];
        let mut fields = inner.split('|');
        let index = fields.next().and_then(|i| i.parse::<usize>().ok());
        match (index, fields.next(), fields.next()) {
            (Some(i), Some(one), Some(many)) => out.push(Piece::Plural(i, one, many)),
            (Some(i), _, _) => out.push(Piece::Arg(i)),
            (None, _, _) => {
                out.push(Piece::Arg(next));
                next += 1;
            }
        }
        rest = &rest[open + close + 1..];
    }
    if !rest.is_empty() {
        out.push(Piece::Text(rest));
    }
    out
}

static PARSED: LazyLock<Vec<Template>> =
    LazyLock::new(|| TEMPLATES.iter().map(|(en, de)| Template { parts: english_parts(en), kinds: kinds(en), german: german_pieces(de) }).collect());

/// What a placeholder may hold: anything, a number (`{#}`), or a plural ending (`{s}`).
#[derive(Clone, Copy, PartialEq)]
enum Kind {
    Any,
    Number,
    Plural,
}

fn kinds(p: &str) -> Vec<Kind> {
    let mut out = Vec::new();
    let mut rest = p;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}') else { break };
        out.push(match &rest[open + 1..open + close] {
            "#" => Kind::Number,
            "s" => Kind::Plural,
            _ => Kind::Any,
        });
        rest = &rest[open + close + 1..];
    }
    out
}

fn fits(kind: Kind, cap: &str) -> bool {
    match kind {
        Kind::Any => !cap.is_empty(),
        Kind::Number => !cap.is_empty() && cap.chars().all(|c| c.is_ascii_digit() || matches!(c, '.' | ',' | ' ')),
        Kind::Plural => matches!(cap, "" | "s" | "es"),
    }
}

/// The placeholders' values if `s` matches the pattern `parts`.
fn captures<'a>(parts: &[&str], s: &'a str) -> Option<Vec<&'a str>> {
    let (first, others) = parts.split_first()?;
    let mut rest = s.strip_prefix(first)?;
    let mut caps = Vec::with_capacity(others.len());
    for (i, part) in others.iter().enumerate() {
        if i + 1 == others.len() {
            let cap = rest.strip_suffix(part)?;
            caps.push(cap);
            rest = "";
        } else if part.is_empty() {
            caps.push("");
        } else {
            let k = rest.find(part)?;
            caps.push(&rest[..k]);
            rest = &rest[k + part.len()..];
        }
    }
    rest.is_empty().then_some(caps)
}

fn templated(text: &str, depth: usize) -> Option<String> {
    if depth > 1 {
        return None;
    }
    for t in PARSED.iter() {
        let Some(caps) = captures(&t.parts, text) else { continue };
        // Each placeholder must hold what it stands for, and none may be the whole label.
        if caps.iter().zip(t.kinds.iter()).any(|(c, k)| !fits(*k, c)) || caps.iter().any(|c| c.len() == text.len()) {
            continue;
        }
        let mut out = String::with_capacity(text.len() + 16);
        for piece in &t.german {
            match piece {
                Piece::Text(s) => out.push_str(s),
                Piece::Arg(i) => {
                    let cap = caps.get(*i).copied().unwrap_or("");
                    match exact(cap) {
                        Some(g) => out.push_str(g),
                        None => match templated(cap, depth + 1) {
                            Some(g) => out.push_str(&g),
                            None => out.push_str(cap),
                        },
                    }
                }
                Piece::Plural(i, one, many) => out.push_str(if caps.get(*i).map(|c| c.trim()) == Some("1") { one } else { many }),
            }
        }
        return Some(out);
    }
    None
}

