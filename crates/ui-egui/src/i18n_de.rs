#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_labels_and_templates() {
        assert_eq!(translate("File").as_deref(), Some("Datei"));
        assert_eq!(translate("Undo Rotate page").as_deref(), Some("Rückgängig: Seite drehen"));
        assert_eq!(translate("1 page").as_deref(), Some("1 Seite"));
        assert_eq!(translate("3 pages").as_deref(), Some("3 Seiten"));
        assert_eq!(translate("Exported 1 image").as_deref(), Some("1 Bild exportiert"));
        assert_eq!(translate("Exported 4 images").as_deref(), Some("4 Bilder exportiert"));
        assert_eq!(translate("Page 3 of 10").as_deref(), Some("Seite 3 von 10"));
        assert_eq!(translate("MODIFY PAGE").as_deref(), Some("SEITE ÄNDERN"));
        assert_eq!(translate("Rotate pages · Insert pages").as_deref(), Some("Seiten drehen · Seiten einfügen"));
        assert_eq!(translate("Lageplan · Rev. A"), None);
        assert_eq!(translate("CivilOps PDF 0.1.2 has been downloaded.").as_deref(), Some("CivilOps PDF 0.1.2 ist heruntergeladen."));
        assert_eq!(
            translate("Couldn't check for updates: this copy wasn't set up with the CivilOps PDF installer, so it can't update itself").as_deref(),
            Some(
                "Suche nach Updates fehlgeschlagen: dieses Programm wurde nicht mit dem Installer von CivilOps PDF eingerichtet und kann sich deshalb nicht selbst aktualisieren"
            )
        );
        assert_eq!(translate("Save changes to “Plan.pdf” before closing?").as_deref(), Some("Änderungen an „Plan.pdf“ vor dem Schließen speichern?"));
        // Unknown text, numbers and document content stay as they are.
        assert_eq!(translate("Lageplan Kobern"), None);
        assert_eq!(translate("12,34 m"), None);
        assert_eq!(translate("x"), None);
        // No German label contains an em dash.
        for (_, de) in EXACT.iter().chain(TEMPLATES) {
            assert!(!de.contains('—'), "{de}");
        }
        // Every template parses into as many parts as it has placeholders.
        for t in PARSED.iter() {
            assert!(!t.parts.is_empty());
        }
    }
}
